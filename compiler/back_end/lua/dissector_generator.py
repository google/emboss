_LUA_RESERVED_WORDS = frozenset(
    (
        "and",
        "break",
        "do",
        "else",
        "elseif",
        "end",
        "false",
        "for",
        "function",
        "goto",
        "if",
        "in",
        "local",
        "nil",
        "not",
        "or",
        "repeat",
        "return",
        "then",
        "true",
        "until",
        "while",
    )
)


_BANNER = "-- Generated by the Emboss Wireshark Lua dissector backend; do not edit."


def _sanitize_lua_identifier(name):
    """Returns a syntactically valid Lua identifier derived from `name`."""
    sanitized = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if not sanitized or sanitized[0].isdigit():
        sanitized = "_" + sanitized
    if sanitized in _LUA_RESERVED_WORDS:
        sanitized = sanitized + "_"
    return sanitized


def _lua_string_escape(value):
    """Escapes a Python string for inclusion in a Lua double-quoted string."""
    out = []
    for ch in value:
        if ch == "\\" or ch == '"':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append("\\{:03d}".format(ord(ch)))
        else:
            out.append(ch)
    return "".join(out)


def _quote(value):
    return '"' + _lua_string_escape(value) + '"'


def _module_protocol_name(module):
    """Returns the protocol name for `module`.

    If the module has a `[(wireshark) protocol: "..."]` attribute, its value
    is used; otherwise the protocol name is `emboss_` followed by the source
    file's basename.
    """
    attr = ir_util.get_attribute(module.attribute, attributes.Attribute.PROTOCOL)
    if attr and attr.string_constant.text:
        return _sanitize_lua_identifier(attr.string_constant.text)
    base = os.path.basename(module.source_file_name or "")
    if base.endswith(".emb"):
        base = base[:-4]
    if not base:
        return "emboss"
    # Wireshark refuses to register a second protocol under the name of a
    # built-in one ("there cannot be two protocols with the same name"), and
    # plausible module names such as data, udp, can, usb or frame all collide
    # with one.  Prefix the derived name so that it never does.
    return "emboss_" + _sanitize_lua_identifier(base)


def _filter_override(attribute_list):
    """Returns the `(wireshark) filter` override on a struct or field, or None."""
    attr = ir_util.get_attribute(attribute_list, attributes.Attribute.FILTER)
    if attr and attr.string_constant.text:
        return attr.string_constant.text
    return None


def _doc_text(documentation_list):
    """Joins all `--` documentation strings, ignoring `#` comments."""
    parts = [doc.text.strip() for doc in documentation_list if doc.text]
    return " ".join(part for part in parts if part)


def _local_name(canonical_name):
    """Returns the last segment of a CanonicalName's object_path."""
    return canonical_name.object_path[-1]


def _type_key(type_def):
    """Returns a hashable key identifying `type_def`."""
    canonical_name = type_def.name.canonical_name
    return (canonical_name.module_file, tuple(canonical_name.object_path))


def _lua_bool(value):
    return "true" if value else "false"


def _qualified_lua_name(canonical_name):
    """Returns a Lua-safe joined name for an IR object's canonical path."""
    return "_".join(
        _sanitize_lua_identifier(part) for part in canonical_name.object_path
    )


# Enum value tables and per-struct dissect functions are stored in two module
# level tables (`enums` and `dissect`) rather than as individual locals: Lua
# allows at most 200 local variables per function, including the main chunk, so
# a module with a couple of hundred types would otherwise fail to load.
def _enum_values_var(canonical_name, width_bits):
    return "enums.{}_{}".format(_qualified_lua_name(canonical_name), width_bits)


def _dissector_function(canonical_name):
    return "dissect." + _qualified_lua_name(canonical_name)


def _proto_var(protocol_name):
    return protocol_name + "_proto"


# Parameter lists of the generated dissect functions.  A `bits` dissector also
# takes the byte order of the enclosing struct field, because one named `bits`
# may be used from both big- and little-endian structs.
_STRUCT_PARAMS = "buffer, pinfo, tree, offset"
_BITS_PARAMS = "buffer, pinfo, tree, offset, little_endian"

# Emitted once, when some byte-struct field is a `Bcd`.  Wireshark has no
# packed-BCD field type, so the value is decoded here and added explicitly;
# the ProtoField itself is a plain unsigned integer so it can be filtered on.
_BCD_HELPER = """\
-- Adds the packed-BCD `range` (two decimal digits per byte, most significant
-- digit first) to `tree` as `field`, and returns its value.  If a nibble isn't
-- a decimal digit, the raw bytes are added instead and the result is nil.
local function add_bcd(tree, field, range, little_endian)
  local len = range:len()
  local value = 0
  for i = 0, len - 1 do
    local byte = range:range(little_endian and (len - 1 - i) or i, 1):uint()
    local high, low = math.floor(byte / 16), byte % 16
    if high > 9 or low > 9 then
      tree:add(field, range):append_text(" [invalid BCD]")
      return nil
    end
    value = value * 100 + high * 10 + low
  end
  if len > 4 then
    -- A uint64 field needs a UInt64 object rather than a Lua number.
    local low32 = value % 4294967296
    tree:add(field, range, UInt64(low32, math.floor((value - low32) / 4294967296)))
  else
    tree:add(field, range, value)
  end
  return value
end"""


_PRIMITIVE_TYPE_NAMES = ("UInt", "Int", "Bcd", "Flag", "Float")


def _primitive_name_of(type_ir):
    """If `type_ir` is a prelude primitive, returns its name; otherwise None."""
    if not type_ir.has_field("atomic_type"):
        return None
    ref = type_ir.atomic_type.reference
    if not ref or not ref.canonical_name:
        return None
    if ref.canonical_name.module_file != "":
        return None
    path = list(ref.canonical_name.object_path)
    if len(path) != 1:
        return None
    name = path[0]
    return name if name in _PRIMITIVE_TYPE_NAMES else None


def _referenced_type_definition(type_ir, ir):
    """Returns the TypeDefinition referenced by `type_ir`, or None."""
    if not type_ir.has_field("atomic_type"):
        return None
    ref = type_ir.atomic_type.reference
    if not ref or not ref.canonical_name:
        return None
    if ref.canonical_name.module_file == "":
        return None
    return ir_util.find_object_or_none(ref, ir)


def _wireshark_int_type(primitive, size_in_bits):
    """Maps an integer-like primitive + size in bits to a Wireshark field type."""
    size_in_bytes = (size_in_bits + 7) // 8
    if primitive == "Int":
        prefix = "int"
    else:
        prefix = "uint"
    if size_in_bytes <= 1:
        return prefix + "8"
    if size_in_bytes <= 2:
        return prefix + "16"
    if size_in_bytes <= 4:
        return prefix + "32"
    return prefix + "64"


def _wireshark_float_type(size_in_bits):
    return "float" if size_in_bits == 32 else "double"


def _byte_order_of_field(field_ir):
    """Returns 'BigEndian', 'LittleEndian', or '' for the given field."""
    attr = ir_util.get_attribute(field_ir.attribute, "byte_order")
    if attr and attr.string_constant.text:
        return attr.string_constant.text
    return ""


def _add_call(byte_order):
    """Returns the appropriate `subtree:add*` call form for `byte_order`."""
    if byte_order == "LittleEndian":
        return "add_le"
    return "add"


# ---------------------------------------------------------------------------
# Expression translation
#
# Conditional fields, dynamically-located fields, and variable-length arrays
# all need to evaluate an Emboss expression at dissection time.  These helpers
# translate an Emboss IR Expression into a Lua expression string, or return
# None when the expression refers to something the back end can't (yet)
# express.  In the latter case the dependent field is skipped with a comment,
# preserving the "always emit valid Lua" guarantee.
# ---------------------------------------------------------------------------


# Emboss operators that map directly onto a Lua infix operator.  ADDITION,
# MULTIPLICATION, AND, and OR are associative and may appear with more than two
# arguments; the comparison operators are strictly binary.
_LUA_INFIX_OPERATORS = {
    ir_data.FunctionMapping.ADDITION: "+",
    ir_data.FunctionMapping.SUBTRACTION: "-",
    ir_data.FunctionMapping.MULTIPLICATION: "*",
    ir_data.FunctionMapping.EQUALITY: "==",
    ir_data.FunctionMapping.INEQUALITY: "~=",
    ir_data.FunctionMapping.AND: "and",
    ir_data.FunctionMapping.OR: "or",
    ir_data.FunctionMapping.LESS: "<",
    ir_data.FunctionMapping.LESS_OR_EQUAL: "<=",
    ir_data.FunctionMapping.GREATER: ">",
    ir_data.FunctionMapping.GREATER_OR_EQUAL: ">=",
}


def _collect_field_references(expression, out):
    """Appends every FieldReference appearing in `expression` to `out`."""
    if expression is None or expression.which_expression is None:
        return
    kind = expression.which_expression
    if kind == "field_reference":
        out.append(expression.field_reference)
    elif kind == "function":
        for arg in expression.function.args:
            _collect_field_references(arg, out)


def _translate_expression(expression, resolve_field):
    """Translates an Emboss Expression into a Lua expression string.

    Arguments:
      expression: the ir_data.Expression to translate.
      resolve_field: a callable mapping an ir_data.FieldReference to the Lua
        text holding that field's runtime value, or None if the value isn't
        available.

    Returns:
      A Lua expression string, or None if the expression can't be fully
      translated.
    """
    if expression is None or expression.which_expression is None:
        return None
    # Constant subexpressions -- including enum constants such as
    # `Kind.RESPONSE` -- fold to a literal, exactly as the C++ back end does.
    # This also covers the `constant`, `constant_reference`, and
    # `boolean_constant` expression kinds.
    value = ir_util.constant_value(expression)
    if value is not None:
        if isinstance(value, bool):
            return "true" if value else "false"
        return str(value)
    kind = expression.which_expression
    if kind == "field_reference":
        return resolve_field(expression.field_reference)
    if kind == "function":
        return _translate_function(expression.function, resolve_field)
    # A non-constant builtin_reference (e.g. `$size_in_bytes`) is not supported.
    return None


def _translate_function(function, resolve_field):
    """Translates an ir_data.Function into a Lua expression string, or None."""
    args = [_translate_expression(arg, resolve_field) for arg in function.args]
    if any(arg is None for arg in args):
        return None
    if function.function == ir_data.FunctionMapping.MAXIMUM:
        return "math.max(" + ", ".join(args) + ")"
    operator = _LUA_INFIX_OPERATORS.get(function.function)
    if operator is None or len(args) < 2:
        # CHOICE (?:), PRESENCE, the bound functions, and unary operators are
        # not supported.
        return None
    return "(" + (" " + operator + " ").join(args) + ")"


def _value_reader(primitive, size, byte_order):
    """Returns the TvbRange reader method for capturing a scalar value, or None.

    Only fixed-size integer-like fields of 1-4 bytes are capturable; Wireshark's
    `TvbRange:uint`/`:int` accessors return a plain Lua number for those widths.
    Wider or non-integer fields return None and simply aren't captured, so any
    expression referring to them is skipped rather than mistranslated.  (`Bcd`
    values are captured from `add_bcd` instead; see _emit_primitive_field.)
    """
    if size is None or size < 1 or size > 4:
        return None
    little_endian = byte_order == "LittleEndian"
    if primitive == "Int":
        return "le_int" if little_endian else "int"
    if primitive in ("UInt", "Enum"):
        return "le_uint" if little_endian else "uint"
    return None


def _field_references(field):
    """Returns the hashable names of the sibling fields `field` depends on.

    These are the single-segment field references in its existence condition,
    location and (for arrays) element count, in order of first appearance.
    """
    refs = []
    _collect_field_references(field.existence_condition, refs)
    # Virtual fields have no physical location, and aren't emitted.
    if field.location is not None:
        _collect_field_references(field.location.start, refs)
        _collect_field_references(field.location.size, refs)
    if (
        field.type is not None
        and field.type.has_field("array_type")
        and (field.type.array_type.which_size == "element_count")
    ):
        _collect_field_references(field.type.array_type.element_count, refs)
    keys = []
    for ref in refs:
        if len(ref.path) == 1:
            key = ir_util.hashable_form_of_reference(ref.path[0])
            if key not in keys:
                keys.append(key)
    return keys


class _FieldEmitter:
    """Accumulates ProtoField declarations and dissector body lines."""

    def __init__(self, ir, protocol_name, filter_root):
        self._ir = ir
        self._protocol_name = protocol_name
        # First segment of every field's display-filter name.
        self._filter_root = filter_root
        # field_decls: list of (key, declaration) preserving definition order.
        self.field_decls = []
        # struct_bodies: list of (canonical_name, parameter_list, [body_lines])
        self.struct_bodies = []
        # struct_size_bytes: dict mapping canonical_name tuple -> size in bytes
        # for fixed-size byte structs; None if unknown.
        self._struct_size_bytes = {}
        self.errors = []
        # Per-struct expression-translation state, reset in visit_struct():
        #   _referenced:    hashable canonical names of fields referenced by some
        #                   sibling's condition / location / array-count.
        #   _value_locals:  hashable canonical name -> Lua local holding the
        #                   captured runtime value of that field.
        #   _nullable_locals: the value locals that may hold nil at run time
        #                   (a `Bcd` that didn't decode); fields depending on
        #                   one are dissected only when it isn't nil.
        self._referenced = set()
        self._value_locals = {}
        self._nullable_locals = set()
        # Whether the generated script needs the add_bcd helper.
        self.needs_bcd_helper = False
        # Enum value-strings tables, one per (enum, field width) actually used,
        # as Lua text in first-use order.  _enum_table_vars caches their names
        # by (_type_key(), width); None when no value of the enum fits.
        self.enum_tables = []
        self._enum_table_vars = {}
        # _type_key() of each anonymous `bits` -> byte size of the struct field
        # holding it.  Filled in while visiting the enclosing struct, which
        # _all_types() always yields before the anonymous type itself.
        self._anonymous_bits_container = {}

    def _emit_field_decl(self, key, declaration):
        self.field_decls.append((key, declaration))

    def _resolve_field(self, field_reference):
        """Returns the Lua local holding a referenced field's value, or None."""
        if len(field_reference.path) != 1:
            return None
        key = ir_util.hashable_form_of_reference(field_reference.path[0])
        return self._value_locals.get(key)

    def _translate(self, expression):
        """Translates `expression` to Lua, resolving sibling field references."""
        return _translate_expression(expression, self._resolve_field)

    def _compute_referenced_fields(self, struct):
        """Collects fields referenced by sibling conditions/locations/counts."""
        referenced = set()
        for field in struct.field:
            referenced.update(_field_references(field))
        return referenced

    def _nil_guards(self, field):
        """Returns Lua conditions requiring `field`'s nullable inputs be set."""
        guards = []
        for key in _field_references(field):
            var = self._value_locals.get(key)
            if var in self._nullable_locals and var + " ~= nil" not in guards:
                guards.append(var + " ~= nil")
        return guards

    def _maybe_capture_value(
        self, field, primitive, start_lua, size, byte_order, body_lines
    ):
        """Emits a value-capturing local for `field` if a sibling references it.

        Only called for unconditional, fixed-offset scalar fields, so the local
        is always in scope wherever a later expression uses it.
        """
        key = ir_util.hashable_form_of_reference(field.name)
        if key not in self._referenced:
            return
        reader = _value_reader(primitive, size, byte_order)
        if reader is None:
            return
        var = "val_" + _qualified_lua_name(field.name.canonical_name)
        body_lines.append(
            "local {var} = buffer(offset + {start}, {size}):{reader}()".format(
                var=var, start=start_lua, size=size, reader=reader
            )
        )
        self._value_locals[key] = var

    def _proto_filter(self, *segments):
        return ".".join((self._filter_root,) + tuple(segments))

    def _enum_valuestring(self, enum_type_def, width_bits):
        """Returns the value-strings table for an enum read at `width_bits`.

        The table is emitted on first use; the result is None (no table) when
        none of the enum's values fits in `width_bits`.
        """
        cache_key = (_type_key(enum_type_def), width_bits)
        if cache_key not in self._enum_table_vars:
            table = _generate_enum_values_table(enum_type_def, width_bits)
            var = None
            if table is not None:
                self.enum_tables.append(table)
                var = _enum_values_var(enum_type_def.name.canonical_name, width_bits)
            self._enum_table_vars[cache_key] = var
        return self._enum_table_vars[cache_key]

    def _emit_protofield(
        self,
        key,
        proto_filter,
        ws_type,
        display_name,
        base="base.DEC",
        valuestring=None,
        mask=None,
        description=None,
    ):
        """Emits one Lua `ProtoField.<ws_type>(...)` declaration.

        Wireshark's ProtoField positional signature is
        `ProtoField.<type>(abbr, name, base, valuestring, mask, desc)`.
        Trailing args may be omitted but must be padded with `nil` when an
        argument further to the right is supplied.
        """
        parts = [_quote(proto_filter), _quote(display_name)]
        need_base = bool(valuestring) or bool(mask) or bool(description)
        need_valuestring = bool(mask) or bool(description) or bool(valuestring)
        need_mask = bool(mask) or bool(description)
        need_desc = bool(description)
        if need_base:
            parts.append(base)
        if need_valuestring:
            parts.append(valuestring if valuestring else "nil")
        if need_mask:
            parts.append(mask if mask else "nil")
        if need_desc:
            parts.append(_quote(description))
        decl = "ProtoField.{}({})".format(ws_type, ", ".join(parts))
        self._emit_field_decl(key, decl)

    def visit_struct(self, type_def):
        struct = type_def.structure
        # Reset per-struct expression-translation state.  Value locals are only
        # emitted for fields some sibling actually refers to, so structs with no
        # conditional / dynamic fields produce exactly the same output as before.
        self._referenced = self._compute_referenced_fields(struct)
        self._value_locals = {}
        self._nullable_locals = set()
        if type_def.addressable_unit == ir_data.AddressableUnit.BIT:
            self._emit_bits_type(type_def)
            return
        # The struct filter qualifies every contained field, so it must be
        # unique across the module.  Use the override if present; otherwise
        # the dotted canonical path of the type (e.g. `parent.child`).
        struct_filter = _filter_override(type_def.attribute) or ".".join(
            _sanitize_lua_identifier(part)
            for part in type_def.name.canonical_name.object_path
        )
        body_lines = []
        body_lines.append(
            'local subtree = tree:add({}_proto, buffer(offset), "{}")'.format(
                self._protocol_name,
                _local_name(type_def.name.canonical_name),
            )
        )

        self._emit_byte_struct_body(type_def, struct, struct_filter, body_lines)
        self.struct_bodies.append(
            (type_def.name.canonical_name, _STRUCT_PARAMS, body_lines)
        )

    def _field_filter_path(self, struct_filter, field_ir):
        override = _filter_override(field_ir.attribute)
        last = override or _sanitize_lua_identifier(
            _local_name(field_ir.name.canonical_name)
        )
        return struct_filter + "." + last

    def _emit_byte_struct_body(self, type_def, struct, struct_filter, body_lines):
        protocol_filter_base = struct_filter
        for index in struct.fields_in_dependency_order or list(
            range(len(struct.field))
        ):
            field = struct.field[index]
            self._emit_byte_field(
                type_def, struct, field, protocol_filter_base, body_lines
            )

    def _emit_byte_field(self, type_def, struct, field, struct_filter, body_lines):
        if ir_util.field_is_virtual(field):
            # Virtual fields (including the synthetic `$size_in_bytes`,
            # `$max_size_in_bytes`, and `$min_size_in_bytes`) have no on-wire
            # representation, so the dissector simply doesn't emit anything
            # for them.
            return

        field_name = _local_name(field.name.canonical_name)

        # Presence condition.  Unconditional fields get no wrapper; a
        # conditional field whose condition can't be translated is skipped.
        conditional = not _is_unconditional(field)
        condition_lua = None
        if conditional:
            condition_lua = self._translate(field.existence_condition)
            if condition_lua is None:
                body_lines.append(
                    "-- skipped conditional field {} (unsupported condition)".format(
                        field_name
                    )
                )
                return
        # A value that failed to decode (so far only an invalid `Bcd`) leaves
        # its local nil; a field whose presence or placement depends on one is
        # dissected only when the value is known.
        guards = self._nil_guards(field)
        if guards:
            if conditional:
                guards.append(condition_lua)
            condition_lua = " and ".join(guards)
            conditional = True

        # Field location.  A constant start renders to an integer literal, so
        # fixed-offset fields produce byte-identical output to the prior
        # constant-only implementation.
        start_lua = self._translate(field.location.start)
        if start_lua is None:
            body_lines.append("-- skipped dynamic-location field {}".format(field_name))
            return
        size = ir_util.constant_value(field.location.size)

        proto_filter = self._proto_filter(self._field_filter_path(struct_filter, field))
        key = _qualified_lua_name(type_def.name.canonical_name) + "." + field_name
        doc = _doc_text(field.documentation)
        byte_order = _byte_order_of_field(field)

        type_ir = field.type
        primitive = _primitive_name_of(type_ir)
        referenced_type = (
            None if primitive else _referenced_type_definition(type_ir, self._ir)
        )
        is_enum = referenced_type is not None and referenced_type.has_field(
            "enumeration"
        )

        # Capture this field's value for any sibling expression that refers to
        # it.  Only unconditional, fixed-size scalar fields are eligible, so the
        # local is always emitted at function-body scope (never inside the `if`
        # wrapper below) and is therefore in scope wherever it is used.
        if not conditional:
            capture_primitive = primitive or ("Enum" if is_enum else None)
            if capture_primitive is not None:
                self._maybe_capture_value(
                    field, capture_primitive, start_lua, size, byte_order, body_lines
                )
        # A `Bcd` is captured from the decoded value add_bcd returns, which is
        # nil for an invalid encoding.
        value_var = None
        if primitive == "Bcd" and not conditional and size is not None:
            field_key = ir_util.hashable_form_of_reference(field.name)
            if field_key in self._referenced:
                value_var = "val_" + _qualified_lua_name(field.name.canonical_name)
                self._value_locals[field_key] = value_var
                self._nullable_locals.add(value_var)

        field_lines = []
        if type_ir.has_field("array_type"):
            self._emit_byte_array_field(
                type_def,
                field,
                type_ir,
                start_lua,
                size,
                proto_filter,
                key,
                doc,
                byte_order,
                field_lines,
            )
        elif primitive:
            if size is None:
                field_lines.append(
                    "-- skipped dynamic-size field {}".format(field_name)
                )
            else:
                self._emit_primitive_field(
                    primitive,
                    field_name,
                    proto_filter,
                    key,
                    start_lua,
                    size,
                    doc,
                    byte_order,
                    field_lines,
                    value_var,
                )
        elif referenced_type is None:
            field_lines.append(
                "-- skipped field with unsupported type: {}".format(field_name)
            )
        elif is_enum:
            if size is None:
                field_lines.append(
                    "-- skipped dynamic-size field {}".format(field_name)
                )
            else:
                self._emit_enum_field(
                    referenced_type,
                    field_name,
                    proto_filter,
                    key,
                    start_lua,
                    size,
                    doc,
                    byte_order,
                    field_lines,
                )
        elif referenced_type.has_field("structure"):
            self._emit_substruct_field(
                referenced_type,
                field_name,
                start_lua,
                size,
                doc,
                byte_order,
                field_lines,
            )
        else:
            field_lines.append(
                "-- skipped field with unsupported type: {}".format(field_name)
            )

        if conditional:
            body_lines.append("if {} then".format(condition_lua))
            body_lines.extend("  " + line for line in field_lines)
            body_lines.append("end")
        else:
            body_lines.extend(field_lines)

    def _emit_primitive_field(
        self,
        primitive,
        field_name,
        proto_filter,
        key,
        start,
        size,
        doc,
        byte_order,
        body_lines,
        value_var=None,
    ):
        size_in_bits = size * 8
        if primitive == "Flag":
            ws_type = "bool"
        elif primitive == "Float":
            ws_type = _wireshark_float_type(size_in_bits)
        else:
            ws_type = _wireshark_int_type(primitive, size_in_bits)
        self._emit_protofield(
            key,
            proto_filter,
            ws_type,
            field_name,
            description=doc or None,
        )
        if primitive == "Bcd":
            self.needs_bcd_helper = True
            call = "add_bcd(subtree, f[{key}], buffer(offset + {start}, {size}), {le})"
            call = call.format(
                key=_quote(key),
                start=start,
                size=size,
                le=_lua_bool(byte_order == "LittleEndian"),
            )
            if value_var:
                call = "local {} = {}".format(value_var, call)
            body_lines.append(call)
            return
        body_lines.append(
            "subtree:{call}(f[{key}], buffer(offset + {start}, {size}))".format(
                call=_add_call(byte_order),
                key=_quote(key),
                start=start,
                size=size,
            )
        )

    def _emit_enum_field(
        self,
        enum_type_def,
        field_name,
        proto_filter,
        key,
        start,
        size,
        doc,
        byte_order,
        body_lines,
    ):
        ws_type = _wireshark_int_type("UInt", size * 8)
        valuestring = self._enum_valuestring(enum_type_def, size * 8)
        self._emit_protofield(
            key,
            proto_filter,
            ws_type,
            field_name,
            valuestring=valuestring,
            description=doc or None,
        )
        body_lines.append(
            "subtree:{call}(f[{key}], buffer(offset + {start}, {size}))".format(
                call=_add_call(byte_order),
                key=_quote(key),
                start=start,
                size=size,
            )
        )

    def _emit_substruct_field(
        self,
        sub_type_def,
        field_name,
        start,
        size,
        doc,
        byte_order,
        body_lines,
    ):
        is_bits = sub_type_def.addressable_unit == ir_data.AddressableUnit.BIT
        if is_bits and size is None:
            body_lines.append(
                "-- skipped dynamic-size bits field {}".format(field_name)
            )
            return
        anonymous = is_bits and bool(sub_type_def.name.is_anonymous)
        if anonymous:
            # The anonymous bits' dissector adds its fields straight to this
            # subtree, reading the whole of this field as its container.
            self._anonymous_bits_container[_type_key(sub_type_def)] = size
        else:
            body_lines.append("-- nested field {}".format(field_name))
        if doc:
            body_lines.append("-- {}".format(doc))
        # A `bits` is read in the byte order of the field that holds it.
        extra = ", " + _lua_bool(byte_order == "LittleEndian") if is_bits else ""
        body_lines.append(
            "{fn}(buffer, pinfo, subtree, offset + {start}{extra})".format(
                fn=_dissector_function(sub_type_def.name.canonical_name),
                start=start,
                extra=extra,
            )
        )

    def _emit_byte_array_field(
        self,
        type_def,
        field,
        type_ir,
        start,
        size,
        proto_filter,
        key,
        doc,
        byte_order,
        body_lines,
    ):
        # Explicit-element-count arrays only (`[n]`, constant or a reference to
        # a sibling length field); auto-sized (`[]`) arrays are skipped.  The
        # element size must be a whole number of bytes.
        array_type = type_ir.array_type
        field_name = _local_name(field.name.canonical_name)
        if array_type.which_size != "element_count":
            body_lines.append("-- skipped auto-sized array field {}".format(field_name))
            return
        element_count = ir_util.constant_value(array_type.element_count)
        if element_count is not None:
            if element_count <= 0:
                body_lines.append("-- skipped empty array field {}".format(field_name))
                return
            count_lua = str(element_count)
        else:
            # A variable element count, e.g. `UInt:8[length]`.  Translatable
            # only if every field it references was captured as a value local.
            count_lua = self._translate(array_type.element_count)
            if count_lua is None:
                body_lines.append(
                    "-- skipped variable-length array field {} "
                    "(unsupported length)".format(field_name)
                )
                return

        element_size_bits = ir_util.fixed_size_of_type_in_bits(
            array_type.base_type, self._ir
        )
        if element_size_bits is None or element_size_bits % 8 != 0:
            body_lines.append(
                "-- skipped array with non-byte element size: {}".format(field_name)
            )
            return
        element_size = element_size_bits // 8
        body_lines.append(
            "-- array field {} ({} elements)".format(field_name, count_lua)
        )

        base_type = array_type.base_type
        primitive = _primitive_name_of(base_type)
        if primitive:
            if primitive == "Flag":
                ws_type = "bool"
            elif primitive == "Float":
                ws_type = _wireshark_float_type(element_size_bits)
            else:
                ws_type = _wireshark_int_type(primitive, element_size_bits)
            self._emit_protofield(
                key,
                proto_filter,
                ws_type,
                field_name,
                description=doc or None,
            )
            body_lines.append("for i = 0, {n} - 1 do".format(n=count_lua))
            if primitive == "Bcd":
                self.needs_bcd_helper = True
                body_lines.append(
                    "  add_bcd(subtree, f[{key}], buffer(offset + {start} + i * "
                    "{esize}, {esize}), {le})".format(
                        key=_quote(key),
                        start=start,
                        esize=element_size,
                        le=_lua_bool(byte_order == "LittleEndian"),
                    )
                )
            else:
                body_lines.append(
                    "  subtree:{call}(f[{key}], buffer(offset + {start} + i * "
                    "{esize}, {esize}))".format(
                        call=_add_call(byte_order),
                        key=_quote(key),
                        start=start,
                        esize=element_size,
                    )
                )
            body_lines.append("end")
            return

        referenced = _referenced_type_definition(base_type, self._ir)
        if referenced and referenced.has_field("enumeration"):
            ws_type = _wireshark_int_type("UInt", element_size_bits)
            valuestring = self._enum_valuestring(referenced, element_size_bits)
            self._emit_protofield(
                key,
                proto_filter,
                ws_type,
                field_name,
                valuestring=valuestring,
                description=doc or None,
            )
            body_lines.append("for i = 0, {n} - 1 do".format(n=count_lua))
            body_lines.append(
                "  subtree:{call}(f[{key}], buffer(offset + {start} + i * "
                "{esize}, {esize}))".format(
                    call=_add_call(byte_order),
                    key=_quote(key),
                    start=start,
                    esize=element_size,
                )
            )
            body_lines.append("end")
            return

        if referenced and referenced.has_field("structure"):
            extra = ""
            if referenced.addressable_unit == ir_data.AddressableUnit.BIT:
                extra = ", " + _lua_bool(byte_order == "LittleEndian")
            body_lines.append("for i = 0, {n} - 1 do".format(n=count_lua))
            body_lines.append(
                "  {fn}(buffer, pinfo, subtree, offset + {start} + i * "
                "{esize}{extra})".format(
                    fn=_dissector_function(referenced.name.canonical_name),
                    start=start,
                    esize=element_size,
                    extra=extra,
                )
            )
            body_lines.append("end")
            return

        body_lines.append("-- skipped array of unsupported type: {}".format(field_name))

    def _emit_bits_type(self, type_def):
        """Emits the dissect function for a `bits` type.

        Emboss reads a `bits` as one unsigned integer spanning the whole struct
        field that holds it, in that field's byte order, and numbers bits from
        the integer's least-significant bit (bit 0).  Each sub-field is
        therefore a ProtoField on that same byte range with the mask
        `((1 << size) - 1) << start`, added with `add_le` or `add` according
        to the enclosing field's byte order, which the caller passes in as
        `little_endian`.
        """
        canonical_name = type_def.name.canonical_name
        container_bytes = self._anonymous_bits_container.get(_type_key(type_def))
        if container_bytes is None:
            # A named `bits` can only be placed in a struct field of exactly
            # its own size, so its fixed size is its container (rounded up
            # for a `bits` that is only ever nested inside other `bits`).
            fixed_size = ir_util.get_integer_attribute(
                type_def.attribute, "fixed_size_in_bits"
            )
            container_bytes = ((fixed_size or 0) + 7) // 8
        anonymous = bool(type_def.name.is_anonymous)
        path = list(canonical_name.object_path)
        if anonymous:
            # An anonymous `bits` is invisible in the source: its fields read
            # as if they belonged to the enclosing struct, so they are named
            # after the struct and added straight to its subtree.
            path = path[:-1]
        struct_filter = _filter_override(type_def.attribute) or ".".join(
            _sanitize_lua_identifier(part) for part in path
        )
        key_prefix = "_".join(_sanitize_lua_identifier(part) for part in path)
        target = "tree" if anonymous else "subtree"
        field_lines = []
        if container_bytes:
            self._emit_bits_fields(
                type_def,
                0,
                container_bytes,
                struct_filter,
                key_prefix,
                target,
                field_lines,
            )
        body_lines = []
        if not anonymous:
            body_lines.append(
                'local subtree = tree:add({}_proto, buffer(offset, {}), "{}")'.format(
                    self._protocol_name, container_bytes, _local_name(canonical_name)
                )
            )
        if field_lines:
            body_lines.append(
                "local range = buffer(offset, {})".format(container_bytes)
            )
            body_lines.append(
                "local add = little_endian and {t}.add_le or {t}.add".format(t=target)
            )
            body_lines.extend(field_lines)
        self.struct_bodies.append((canonical_name, _BITS_PARAMS, body_lines))

    def _emit_bits_fields(
        self,
        bits_type_def,
        bit_offset,
        container_bytes,
        struct_filter,
        key_prefix,
        target,
        body_lines,
    ):
        """Emits masked ProtoFields for the fields of `bits_type_def`.

        `bit_offset` is where this `bits` starts within the container: zero for
        the `bits` the container holds directly, and the nested field's start
        for a `bits` nested inside another `bits`, whose fields are flattened
        into the same container.
        """
        container_bits = container_bytes * 8
        for field in bits_type_def.structure.field:
            if ir_util.field_is_virtual(field):
                continue
            field_name = _local_name(field.name.canonical_name)
            if not _is_unconditional(field):
                body_lines.append("-- skipped conditional field {}".format(field_name))
                continue
            start = ir_util.constant_value(field.location.start)
            size = ir_util.constant_value(field.location.size)
            if start is None or size is None:
                body_lines.append(
                    "-- skipped dynamic-location field {}".format(field_name)
                )
                continue
            start += bit_offset
            if start + size > container_bits:
                body_lines.append(
                    "-- skipped field {} (outside its {}-byte container)".format(
                        field_name, container_bytes
                    )
                )
                continue
            key = key_prefix + "." + field_name
            proto_filter = self._proto_filter(
                self._field_filter_path(struct_filter, field)
            )
            mask = "0x{:0{w}X}".format(
                ((1 << size) - 1) << start, w=container_bytes * 2
            )
            doc = _doc_text(field.documentation)

            primitive = _primitive_name_of(field.type)
            referenced = (
                None if primitive else _referenced_type_definition(field.type, self._ir)
            )
            if primitive == "Flag":
                # `ProtoField.bool` takes the parent's width in bits where the
                # integer constructors take `base`.
                parts = [
                    _quote(proto_filter),
                    _quote(field_name),
                    str(container_bits),
                    "nil",
                    mask,
                ]
                if doc:
                    parts.append(_quote(doc))
                self._emit_field_decl(
                    key, "ProtoField.bool({})".format(", ".join(parts))
                )
            elif primitive in ("UInt", "Int", "Bcd"):
                base = "base.DEC"
                if primitive == "Bcd":
                    # Wireshark can't decode a masked BCD value; show its hex
                    # digits, which read as the decimal digits of the value.
                    base = "base.HEX"
                self._emit_protofield(
                    key,
                    proto_filter,
                    _wireshark_int_type(primitive, container_bits),
                    field_name,
                    base=base,
                    mask=mask,
                    description=doc or None,
                )
            elif referenced is not None and referenced.has_field("enumeration"):
                self._emit_protofield(
                    key,
                    proto_filter,
                    _wireshark_int_type("UInt", container_bits),
                    field_name,
                    valuestring=self._enum_valuestring(referenced, size),
                    mask=mask,
                    description=doc or None,
                )
            elif (
                referenced is not None
                and referenced.has_field("structure")
                and referenced.addressable_unit == ir_data.AddressableUnit.BIT
            ):
                # A nested `bits`: flatten its fields into this container.
                nested_filter = _filter_override(
                    referenced.attribute
                ) or self._field_filter_path(struct_filter, field)
                self._emit_bits_fields(
                    referenced,
                    start,
                    container_bytes,
                    nested_filter,
                    key,
                    target,
                    body_lines,
                )
                continue
            else:
                body_lines.append(
                    "-- skipped bits field with unsupported type: {}".format(field_name)
                )
                continue

            body_lines.append("add({}, f[{}], range)".format(target, _quote(key)))


def _is_unconditional(field):
    """Returns True iff the field is unconditionally present."""
    cond = field.existence_condition
    if cond is None:
        return True
    if cond.has_field("boolean_constant"):
        return cond.boolean_constant.value is True
    if cond.type and cond.type.boolean and cond.type.boolean.has_field("value"):
        return cond.type.boolean.value is True
    return False


def _generate_enum_values_table(type_def, width_bits):
    """Returns the Lua value-strings table for `type_def` read at `width_bits`.

    Keys are the raw unsigned field value, which is what Wireshark looks up: a
    negative enum value is keyed by its two's-complement encoding in the enum's
    `maximum_bits`, and values that can't occur in a field `width_bits` wide
    are left out.  Where several names share one value the first wins, as in
    the C++ back end's TryToGetNameFromEnum.  Returns None if no value fits.
    """
    max_bits = ir_util.get_integer_attribute(type_def.attribute, "maximum_bits")
    modulus = 1 << (max_bits or 64)
    entries = []
    seen = set()
    for value in type_def.enumeration.value:
        if not value.name or not value.value:
            continue
        numeric = ir_util.constant_value(value.value)
        if numeric is None:
            continue
        key = numeric % modulus if numeric < 0 else numeric
        if key in seen or key >= (1 << width_bits):
            continue
        seen.add(key)
        # A decimal literal of 2^63 or more reads as a float in Lua, which
        # then matches nothing; a hex literal wraps to the right integer.
        literal = "0x{:016X}".format(key) if key >= (1 << 63) else str(key)
        entries.append(
            "  [{}] = {},".format(
                literal, _quote(_local_name(value.name.canonical_name))
            )
        )
    if not entries:
        return None
    header = "{} = {{".format(
        _enum_values_var(type_def.name.canonical_name, width_bits)
    )
    return "\n".join([header] + entries + ["}"])


def _propagate_defaults_and_verify_attributes(ir):
    """Validates `(wireshark)` back-end attributes throughout the IR."""
    return attribute_util.check_attributes_in_ir(
        ir,
        back_end=attributes.BACK_END,
        types=attributes.TYPES,
        module_attributes=attributes.Scope.MODULE,
        struct_attributes=attributes.Scope.STRUCT,
        bits_attributes=attributes.Scope.BITS,
        structure_physical_field_attributes=attributes.Scope.STRUCT_PHYSICAL_FIELD,
    )


def _module_has_dissectable_root(module):
    for type_def in module.type:
        if type_def.has_field("structure"):
            return True
    return False


def _is_byte_struct(type_def):
    return (
        type_def.has_field("structure")
        and type_def.addressable_unit == ir_data.AddressableUnit.BYTE
    )


def _all_types(module):
    """Yields every TypeDefinition in `module`, recursing into subtypes.

    Order is preorder (parent before children) and otherwise preserves the
    order types appear in the source file.
    """

    def walk(type_def):
        yield type_def
        for sub in type_def.subtype:
            yield from walk(sub)

    for top in module.type:
        yield from walk(top)


def generate_dissector(ir):
    """Generates a Wireshark Lua dissector from `ir`.

    Returns:
      (text, errors) — `text` is the Lua source on success, and `errors` is
      a list of error lists in the same shape as the C++ backend uses.
    """
    errors = _propagate_defaults_and_verify_attributes(ir)
    if errors:
        return "", errors

    module = ir.module[0]
    protocol_name = _module_protocol_name(module)
    proto_var = _proto_var(protocol_name)
    # Root of every field's display-filter name: a module-level
    # `[(wireshark) filter: "..."]` if present, otherwise the protocol name.
    filter_root = _filter_override(module.attribute) or protocol_name

    lines = [_BANNER]
    if module.source_file_name:
        lines.append("-- Source: " + module.source_file_name)
    lines.append(
        "-- Protocol {} (override with a module-level"
        ' [(wireshark) protocol: "..."] attribute).'.format(_quote(protocol_name))
    )
    lines.append("")

    module_doc = _doc_text(module.documentation)
    if module_doc:
        lines.append("-- " + module_doc)
        lines.append("")

    lines.append(
        "local {proto} = Proto({name}, {desc})".format(
            proto=proto_var,
            name=_quote(protocol_name),
            desc=_quote(protocol_name + " (Emboss)"),
        )
    )
    lines.append("")

    # Build struct bodies / field declarations for every struct / bits
    # (including those nested in other structs).
    emitter = _FieldEmitter(ir, protocol_name, filter_root)
    for type_def in _all_types(module):
        if type_def.has_field("structure"):
            emitter.visit_struct(type_def)

    if emitter.enum_tables:
        lines.append(
            "-- Enum value names, one table per width an enum is read at.  Keys"
        )
        lines.append(
            "-- are the raw unsigned field value; the first name for a value wins."
        )
        lines.append("local enums = {}")
        lines.extend(emitter.enum_tables)
        lines.append("")

    if emitter.field_decls:
        lines.append("local f = {}")
        for key, decl in emitter.field_decls:
            lines.append("f[{}] = {}".format(_quote(key), decl))
        lines.append("")
        lines.append("{proto}.fields = {{".format(proto=proto_var))
        for key, _ in emitter.field_decls:
            lines.append("  f[{}],".format(_quote(key)))
        lines.append("}")
        lines.append("")

    if emitter.needs_bcd_helper:
        lines.extend(_BCD_HELPER.splitlines())
        lines.append("")

    # All dissect functions live in one table, so dissectors may reference
    # each other regardless of definition order without consuming a Lua local
    # per struct (see _dissector_function).
    if emitter.struct_bodies:
        lines.append("local dissect = {}")
        lines.append("")

    # Per-struct dissector functions.
    for canonical_name, params, body_lines in emitter.struct_bodies:
        lines.append(
            "function {}({})".format(_dissector_function(canonical_name), params)
        )
        for body_line in body_lines:
            lines.append("  " + body_line)
        lines.append("end")
        lines.append("")

    # Top-level dissector.  Pick the root struct from the (wireshark) root
    # module attribute if set; otherwise default to the first struct
    # declared at module scope.  A `bits` can't be a root: it has no byte
    # order of its own (the C++ back end likewise has no view-from-bytes for
    # one).
    root_attr = ir_util.get_attribute(module.attribute, attributes.Attribute.ROOT)
    root = None
    if root_attr:
        requested = root_attr.string_constant.text
        for type_def in module.type:
            if (
                _is_byte_struct(type_def)
                and _local_name(type_def.name.canonical_name) == requested
            ):
                root = type_def
                break
        if root is None:
            return "", [
                [
                    error.error(
                        module.source_file_name,
                        root_attr.source_location,
                        "(wireshark) root references unknown struct {!r}".format(
                            requested
                        ),
                    )
                ]
            ]
    else:
        for type_def in module.type:
            if _is_byte_struct(type_def):
                root = type_def
                break

    lines.append(
        "function {proto}.dissector(buffer, pinfo, tree)".format(proto=proto_var)
    )
    lines.append("  pinfo.cols.protocol = {}".format(_quote(protocol_name.upper())))
    if root is not None:
        lines.append(
            "  {}(buffer, pinfo, tree, 0)".format(
                _dissector_function(root.name.canonical_name)
            )
        )
    else:
        lines.append("  -- No top-level struct found; nothing to dissect.")
    lines.append("end")
    lines.append("")

    register_attr = ir_util.get_attribute(
        module.attribute, attributes.Attribute.REGISTER_ON
    )
    if register_attr:
        registrations, parse_error = _parse_register_on(
            register_attr.string_constant.text
        )
        if parse_error is not None:
            return "", [
                [
                    error.error(
                        module.source_file_name,
                        register_attr.source_location,
                        parse_error,
                    )
                ]
            ]
        for table_name, pattern in registrations:
            lines.append(
                "DissectorTable.get({table}):add({pattern}, {proto})".format(
                    table=_quote(table_name),
                    pattern=pattern,
                    proto=proto_var,
                )
            )
    else:
        lines.append(
            "-- To register this dissector automatically, add a"
            " `[(wireshark) register_on: ...]`"
        )
        lines.append(
            '-- module attribute (e.g. `register_on: "udp.port == 12345"`),'
            " or uncomment:"
        )
        lines.append('-- DissectorTable.get("udp.port"):add(0, {})'.format(proto_var))
    lines.append("")

    return "\n".join(lines), []


_REGISTER_ON_TERM_RE = re.compile(
    r"^\s*([A-Za-z_][A-Za-z0-9_.]*)\s*==\s*(0[xX][0-9A-Fa-f]+|\d+)\s*$"
)
_REGISTER_ON_SPLIT_RE = re.compile(r"\s+or\s+|\s*\|\|\s*", re.IGNORECASE)


def _parse_register_on(value):
    """Parses `(wireshark) register_on` into `[(table_name, pattern_int)]`.

    Returns:
      (registrations, error_message). On success, error_message is None.
      On failure, registrations is an empty list and error_message is a
      string suitable for an error.error(...) call.
    """
    if not value.strip():
        return [], (
            "(wireshark) register_on must contain at least one"
            ' "<table> == <pattern>" expression.'
        )
    terms = _REGISTER_ON_SPLIT_RE.split(value)
    out = []
    for term in terms:
        match = _REGISTER_ON_TERM_RE.match(term)
        if not match:
            return [], (
                "Invalid (wireshark) register_on expression: {!r}. Expected"
                ' one or more "<table> == <integer>" terms separated by'
                ' "or" or "||".'.format(term.strip())
            )
        table_name = match.group(1)
        pattern_text = match.group(2)
        pattern = int(pattern_text, 0)
        out.append((table_name, pattern))
    return out, None
